# 블록 위치 분류 헬퍼
def classify_block_position(block_idx: int, total_blocks: int) -> str:
    """블록의 위치를 분류합니다."""
    if block_idx < total_blocks * 0.33:
        return "앞부분"
    elif block_idx < total_blocks * 0.66:
        return "중간"
    else:
        return "뒷부분"

